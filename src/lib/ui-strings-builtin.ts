// Whether a language has built-in interface text (or only English).
export function hasBuiltinUi(locale: string) {
  return locale.split("-")[0] === "en" || Boolean(matchLocale([locale], Object.keys(BUILTIN)));
}

export function builtinUi(locale: string): UiStrings {
  const n = normalizeLocale(locale) ?? "en";
  const lang = n.split("-")[0];
  return { ...UI_STRINGS_EN, ...BUILTIN[lang], ...(n !== lang ? BUILTIN[n] : undefined) };
}

// English, then built-in, then the workspace's overrides for that language.
export function resolveUi(locale: string, overrides: unknown): UiStrings {
  const out = builtinUi(locale);
  const mine = overrides && typeof overrides === "object" ? (overrides as Record<string, Record<string, unknown>>)[locale] : undefined;
  if (mine && typeof mine === "object") {
    for (const k of UI_STRING_KEYS) {
      const v = mine[k];
      if (typeof v === "string" && v.trim()) out[k] = v.slice(0, 200);
    }
  }
  return out;
}
